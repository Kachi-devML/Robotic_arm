"""
PlatformIO pre-build script: embeds everything in data/ into comms/WebAssets.h
so the web UI is served from firmware flash and LittleFS is not needed.

Wire it up in platformio.ini ([env:esp32s3]; the other envs inherit it):
    extra_scripts = pre:tools/embed_assets.py

It runs on every build and only rewrites the header if the content changed.
Edit files in data/ as usual; just rebuild and upload the firmware.
"""
import sys
from pathlib import Path

MIME = {
    ".html": "text/html; charset=utf-8",
    ".css": "text/css; charset=utf-8",
    ".js": "application/javascript; charset=utf-8",
    ".json": "application/json; charset=utf-8",
    ".svg": "image/svg+xml",
    ".png": "image/png",
    ".ico": "image/x-icon",
    ".txt": "text/plain; charset=utf-8",
}


def generate(project_dir: str) -> None:
    root = Path(project_dir)
    data_dir = root / "data"
    out_file = root / "comms" / "WebAssets.h"

    files = sorted(p for p in data_dir.rglob("*")
                   if p.is_file() and not p.name.startswith("."))
    if not files:
        raise SystemExit("embed_assets: no files found in %s" % data_dir)

    lines = [
        "// AUTO-GENERATED by tools/embed_assets.py -- do not edit by hand.",
        "#pragma once",
        "#include <stddef.h>",
        "#include <stdint.h>",
        "",
        "namespace WebAssets {",
        "struct Asset { const char* path; const char* mime; const uint8_t* data; size_t size; };",
        "",
    ]
    table = []
    for i, f in enumerate(files):
        blob = f.read_bytes()
        url = "/" + f.relative_to(data_dir).as_posix()
        mime = MIME.get(f.suffix.lower(), "application/octet-stream")
        body = ",".join("0x%02x" % b for b in blob)
        lines.append("// %s (%d bytes)" % (url, len(blob)))
        lines.append("static const uint8_t kData%d[] = {%s};" % (i, body))
        table.append('    {"%s", "%s", kData%d, sizeof(kData%d)},' % (url, mime, i, i))
        lines.append("")
    lines.append("static const Asset kAssets[] = {")
    lines.extend(table)
    lines.append("};")
    lines.append("static const size_t kAssetCount = sizeof(kAssets) / sizeof(kAssets[0]);")
    lines.append("}  // namespace WebAssets")
    lines.append("")
    text = "\n".join(lines)

    if not out_file.exists() or out_file.read_text() != text:
        out_file.write_text(text)
        print("embed_assets: wrote %s (%d files)" % (out_file, len(files)))
    else:
        print("embed_assets: %s up to date (%d files)" % (out_file.name, len(files)))


try:
    Import("env")  # noqa: F821  (provided by PlatformIO/SCons)
    generate(env["PROJECT_DIR"])  # noqa: F821
except NameError:
    # Running outside PlatformIO (manual test): python embed_assets.py <project_dir>
    generate(sys.argv[1] if len(sys.argv) > 1 else ".")
